/**
 * Assemble the browser half of JSON Studio.
 *
 * The panel is hand-written in the shipped lazy-factory format, so there is no
 * bundler here: `src/engine.js` is wrapped in its own scope and its public
 * functions are lifted into the factory, then `src/ui.js` runs against them.
 * Both sources are plain ESM with named exports.
 *
 * Usage: node build.mjs [--check]
 */
import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const read = (file) => readFile(path.join(here, file), 'utf8')
const write = (file, text) => writeFile(path.join(here, file), text, 'utf8')

const pkg = JSON.parse(await read('package.json'))
const engine = await read('src/engine.js')
const ui = await read('src/ui.js')

/** Public engine surface the UI relies on. */
const ENGINE_EXPORTS = [
  'analyzeJson',
  'findJsonCandidates',
  'prettyLoose',
  'tokenizeJson',
  'formatValue',
  'minifyValue',
  'sortKeysDeep',
  'escapeJsonString',
  'unescapeJsonString',
  'summarizeValue',
]

/**
 * Turn top-level `export function` / `export const` / `export class` declarations
 * into plain declarations for the shared factory scope. Deliberately narrow: the
 * sources are authored for this build and only use that form.
 * @param source - module source.
 * @returns source without top-level `export ` keywords.
 */
function stripExports(source) {
  return source
    .replace(/^export\s+(?=(?:async\s+)?function\s|const\s|let\s|class\s)/gmu, '')
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gmu, '')
}

for (const name of ENGINE_EXPORTS) {
  if (!new RegExp(`(?:^|\\n)\\s*(?:export\\s+)?(?:async\\s+)?(?:function|const|let)\\s+${name}\\b`, 'u').test(engine)) {
    throw new Error(`src/engine.js does not declare ${name}`)
  }
}

const indent = (text) => text.replace(/^(?=.)/gmu, '  ')

const out = `/**
 * ${pkg.name} — browser half. GENERATED by build.mjs; edit src/ui.js,
 * src/engine.js and rebuild. Registers one main panel and its sidebar icon.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react')
    const h = React.createElement

    const __engine = (() => {
${indent(stripExports(engine))}
      return { ${ENGINE_EXPORTS.join(', ')} }
    })()
    const { ${ENGINE_EXPORTS.join(', ')} } = __engine

${indent(stripExports(ui))}
  },
})
`

await write('client.js', out)
if (process.argv.includes('--check')) {
  execFileSync(process.execPath, ['--check', path.join(here, 'client.js')], { stdio: 'inherit' })
}
console.log(`client.js written: ${out.length} bytes, ${out.split('\n').length} lines`)
